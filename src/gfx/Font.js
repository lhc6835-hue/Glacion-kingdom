export function textWidth(s, scale = 1) { return (s.length * 6 - 1) * scale; }

// Draws text with a 1px dark outline. g: 2D context at pixel resolution.
export function drawText(g, s, x, y, color, scale = 1, outline = '#0d1c1e') {
  x = Math.round(x); y = Math.round(y);
  if (outline) {
    g.fillStyle = outline;
    for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) glyphs(g, s, x + ox * scale, y + oy * scale, scale);
  }
  g.fillStyle = color;
  glyphs(g, s, x, y, scale);
}

function glyphs(g, s, x, y, scale) {
  for (let i = 0; i < s.length; i++) {
    const rows = G[s[i]] || G[' '];
    for (let r = 0; r < 7; r++) {
      const bits = rows[r];
      for (let c = 0; c < 5; c++) if (bits & (16 >> c)) g.fillRect(x + (i * 6 + c) * scale, y + r * scale, scale, scale);
    }
  }
}
